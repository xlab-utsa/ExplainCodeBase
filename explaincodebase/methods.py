"""The summarization methods compared by this project.

``baseline``  the whole codebase in one prompt (split into parts when it is too large).
``hucp``      Method 1, hierarchical: callees are summarized first and their summaries are
              given as context when summarizing the caller.
``iucp``      Method 2, inline: like ``hucp`` but each callee summary is written as a code
              comment directly above the line that calls it.
``llmucp``    Method 3: ``hucp`` plus, for leaf units (that call nothing in the codebase), a
              line-by-line explanation generated by the LLM first.
``docucp``    Method 4: ``hucp`` plus documentation context: the enclosing class and its
              ancestors, and the documentation of library functions the unit calls.
"""

from __future__ import annotations

import json
import logging
import re
from collections import defaultdict
from concurrent.futures import FIRST_COMPLETED, ThreadPoolExecutor, wait
from dataclasses import dataclass
from typing import Callable

from . import prompts
from .docs import documentation_context
from .graph import CallGraph
from .languages import comment_syntax
from .llm import LLM, LLMError
from .parsing import CodeUnit

log = logging.getLogger(__name__)


@dataclass
class Settings:
    max_code_chars: int = 16_000
    max_callee_chars: int = 800
    max_context_chars: int = 16_000
    baseline_max_chars: int = 400_000
    workers: int = 8
    allow_imports: bool = False

    def fit_context(self, context_tokens: int | None, chars_per_token: float = 3.0) -> "Settings":
        """Shrink prompt budgets so prompts fit a model's context window.

        A quarter of the window is left for the answer; code and context share the rest.
        """
        if not context_tokens:
            return self
        budget = int(context_tokens * 0.75 * chars_per_token)
        self.baseline_max_chars = min(self.baseline_max_chars, max(budget - 4_000, 4_000))
        self.max_code_chars = min(self.max_code_chars, max(budget // 2, 2_000))
        self.max_context_chars = min(self.max_context_chars, max(budget // 3, 1_000))
        return self


@dataclass
class Result:
    summaries: dict[str, str]
    errors: dict[str, str]


Progress = Callable[[int, int], None]


class Method:
    key = ""
    title = ""

    def run(self, graph: CallGraph, llm: LLM, settings: Settings, progress: Progress | None = None) -> Result:
        raise NotImplementedError


class HierarchicalMethod(Method):
    """Summarize units callee-first; each unit sees its direct callees' summaries."""

    def sections(self, unit: CodeUnit, callees: list[tuple[CodeUnit, str]], graph: CallGraph,
                 llm: LLM, settings: Settings) -> list[str | None]:
        return [prompts.callee_section(unit, callees, settings.max_callee_chars, settings.max_context_chars)]

    def code(self, unit: CodeUnit, graph: CallGraph, summaries: dict[str, str]) -> str:
        return unit.source

    def build_prompt(self, unit, graph, llm, settings, summaries) -> str:
        callees = [(graph.units[c], summaries[c]) for c in graph.callees(unit.id) if c in summaries]
        sections = self.sections(unit, callees, graph, llm, settings)
        return prompts.summary_prompt(unit, self.code(unit, graph, summaries), sections,
                                      settings.max_code_chars)

    def run(self, graph, llm, settings, progress=None) -> Result:
        summaries: dict[str, str] = {}
        errors: dict[str, str] = {}
        components = graph.components()
        component_of = {uid: i for i, members in enumerate(components) for uid in members}
        waiting_on: list[set[int]] = []
        dependents: dict[int, list[int]] = defaultdict(list)
        for i, members in enumerate(components):
            deps = {component_of[c] for uid in members for c in graph.callees(uid)} - {i}
            waiting_on.append(deps)
            for dep in deps:
                dependents[dep].append(i)
        total, done = len(graph.units), 0

        def process(index: int) -> None:
            # Members of a cycle are summarized in order; later ones see earlier summaries.
            for uid in components[index]:
                unit = graph.units[uid]
                try:
                    summaries[uid] = llm.complete(self.build_prompt(unit, graph, llm, settings, summaries))
                except LLMError as exc:
                    errors[uid] = str(exc)
                    log.error("%s: could not summarize %s: %s", self.key, uid, exc)
                except Exception as exc:  # a bug for one unit should not lose the whole run
                    errors[uid] = f"{type(exc).__name__}: {exc}"
                    log.exception("%s: unexpected error on %s", self.key, uid)

        with ThreadPoolExecutor(max_workers=max(1, settings.workers)) as pool:
            running = {pool.submit(process, i): i for i, deps in enumerate(waiting_on) if not deps}
            while running:
                finished, _ = wait(running, return_when=FIRST_COMPLETED)
                for future in finished:
                    index = running.pop(future)
                    future.result()
                    done += len(components[index])
                    if progress:
                        progress(done, total)
                    for dependent in dependents[index]:
                        waiting_on[dependent].discard(index)
                        if not waiting_on[dependent]:
                            running[pool.submit(process, dependent)] = dependent
        return Result(summaries, errors)


class HUCP(HierarchicalMethod):
    key = "hucp"
    title = "Method 1: hierarchical callee context"


class IUCP(HierarchicalMethod):
    key = "iucp"
    title = "Method 2: callee summaries inlined at call sites"

    def sections(self, unit, callees, graph, llm, settings):
        # Callees whose call line could not be located still get listed, so nothing is lost.
        lines = {number for number, _ in unit.lines}
        placed = {target for call in graph.calls.get(unit.id, []) if call.site.line in lines
                  for target in call.targets}
        leftovers = [(callee, summary) for callee, summary in callees if callee.id not in placed]
        return [prompts.callee_section(unit, leftovers, settings.max_callee_chars, settings.max_context_chars)]

    def code(self, unit, graph, summaries):
        return annotate_calls(unit, graph, summaries)


class LLMUCP(HierarchicalMethod):
    key = "llmucp"
    title = "Method 3: LLM line-by-line explanation for leaf units"

    def sections(self, unit, callees, graph, llm, settings):
        sections = super().sections(unit, callees, graph, llm, settings)
        if not graph.callees(unit.id):
            explanation = llm.complete(prompts.line_explanation_prompt(unit, settings.max_code_chars))
            sections.append(f"# Context: line-by-line explanation of `{unit.qualname}`\n{explanation}")
        return sections


class DOCUCP(HierarchicalMethod):
    key = "docucp"
    title = "Method 4: documentation context"

    def sections(self, unit, callees, graph, llm, settings):
        sections = super().sections(unit, callees, graph, llm, settings)
        sections.append(documentation_context(unit, graph, settings.allow_imports))
        return sections


class Baseline(Method):
    key = "baseline"
    title = "Baseline: whole codebase in one prompt"

    def run(self, graph, llm, settings, progress=None) -> Result:
        units_by_file: dict[str, list[str]] = defaultdict(list)
        for uid, unit in graph.units.items():
            units_by_file[unit.file].append(uid)
        chunks: list[list[str]] = [[]]
        size = 0
        for path in units_by_file:
            length = len(graph.files[path].text)
            if chunks[-1] and size + length > settings.baseline_max_chars:
                chunks.append([])
                size = 0
            chunks[-1].append(path)
            size += length

        summaries: dict[str, str] = {}
        errors: dict[str, str] = {}
        done = 0
        for i, paths in enumerate(chunks):
            files = [(p, graph.files[p].language.name, graph.files[p].text) for p in paths]
            wanted = [uid for p in paths for uid in units_by_file[p]]
            part = f" (part {i + 1} of {len(chunks)})" if len(chunks) > 1 else ""
            for attempt in range(2):  # second attempt asks again for whatever is missing
                missing = [uid for uid in wanted if uid not in summaries]
                if not missing:
                    break
                try:
                    text = llm.complete(prompts.baseline_prompt(files, missing, part), cache_tag=f"try{attempt}")
                except LLMError as exc:
                    for uid in missing:
                        errors[uid] = str(exc)
                    break
                summaries.update(parse_baseline(text, missing))
            for uid in wanted:
                if uid not in summaries:
                    errors.setdefault(uid, "missing from the model's answer")
                else:
                    errors.pop(uid, None)
            done += len(wanted)
            if progress:
                progress(done, len(graph.units))
        return Result(summaries, errors)


METHODS: dict[str, type[Method]] = {cls.key: cls for cls in (Baseline, HUCP, IUCP, LLMUCP, DOCUCP)}


def annotate_calls(unit: CodeUnit, graph: CallGraph, summaries: dict[str, str]) -> str:
    """Return the unit's code with a comment above each line that calls summarized code."""
    opener, closer = comment_syntax(unit.language)
    by_line: dict[int, list[str]] = defaultdict(list)
    for call in graph.calls.get(unit.id, []):
        for target in call.targets:
            if target in summaries and target != unit.id and target not in by_line[call.site.line]:
                by_line[call.site.line].append(target)
    out = []
    for number, text in unit.lines:
        indent = text[: len(text) - len(text.lstrip())]
        for target in by_line.get(number, []):
            callee = graph.units[target]
            note = prompts.one_line(summaries[target])
            out.append(f"{indent}{opener} calls {callee.qualname}: {note}{closer}")
        out.append(text)
    return "\n".join(out)


def parse_baseline(text: str, wanted: list[str]) -> dict[str, str]:
    """Read the baseline's JSON answer; fall back to ``id: summary`` lines."""
    wanted_set = set(wanted)
    cleaned = re.sub(r"^```\w*\s*|```\s*$", "", text.strip(), flags=re.M)
    start, end = cleaned.find("{"), cleaned.rfind("}")
    result: dict[str, str] = {}
    if start != -1 and end > start:
        try:
            data = json.loads(cleaned[start:end + 1])
        except ValueError:
            data = None
        if isinstance(data, dict):
            for key, value in data.items():
                uid = str(key).strip().strip("`")
                if uid in wanted_set:
                    if isinstance(value, list):
                        value = "\n".join(f"- {item}" for item in value)
                    result[uid] = str(value).strip()
            if result:
                return result
    current = None
    for line in text.splitlines():
        stripped = line.strip().lstrip("-*• ").replace("`", "").replace("**", "")
        match = next((uid for uid in wanted if stripped.startswith(uid + ":")), None)
        if match:
            current = match
            result[current] = stripped[len(match) + 1:].strip()
        elif current and stripped:
            result[current] = (result[current] + "\n" + line.strip()).strip()
        elif not stripped:
            current = None
    return {uid: summary for uid, summary in result.items() if summary}
